const FALLBACK_ICON = <AppstoreOutlined />;

/** 菜单 icon 标识 → 图标（注册表外标识统一回退，不猜新图标）。 */
export function resolveMenuIcon(icon: string | null): ReactNode {
  if (!icon) {
    return FALLBACK_ICON;
  }
  return MENU_ICON_MAP[icon.toLowerCase()] ?? FALLBACK_ICON;
}
