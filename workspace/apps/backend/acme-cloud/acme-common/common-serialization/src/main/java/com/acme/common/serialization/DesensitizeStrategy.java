package com.acme.common.serialization;

/**
 * 脱敏策略（FR-025）。枚举新增值兼容、删除/重命名走破坏性变更（BR-015、Backend.md 7.2.2）。
 *
 * <p>策略集（DP-010 定稿）：掩码规则见各枚举值 javadoc；策略缺失与非法输入
 * （长度不足、格式不符）一律显式失败，不静默脱敏、不静默放行（FR-025 异常分支）。
 * 掩码输出不保留原文长度信息（星号段为固定宽度，防止长度侧信道）。</p>
 *
 * @implNote 暂缓 DP-015：使用样例与更细方法级契约随实现补全。
 */
public enum DesensitizeStrategy {

    /** 手机号：保留前 3 位与后 4 位，中间 {@code ****}（Q-008 结论，如 138****5678）；至少 7 位。 */
    PHONE,

    /** 身份证号：保留前 6 位与后 4 位，中间 {@code ********}；至少 10 位。 */
    ID_CARD,

    /** 邮箱：保留本地部分首字符与完整域名（如 a***@example.com）；须含 {@code @} 且本地部分非空。 */
    EMAIL,

    /** 银行卡号：仅保留后 4 位，其余 {@code ****}；至少 8 位。 */
    BANK_CARD,

    /** 中文姓名：保留首字符（姓），其余逐字 {@code *}；至少 2 个字符。 */
    CHINESE_NAME,

    /** 全掩码：固定输出 {@code ****}，不暴露任何字符与长度。 */
    MASK_ALL
}
